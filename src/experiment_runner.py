# Canonical split files generated by fair_data.prepare_all_datasets.
TRAIN_FILES = {
    "D1_original":    "D1_train.csv",
    "D2_fair_causal": "D2_train.csv",
    "D3_resampled":   "D3_train.csv",
}


def _get_d4_test_sets(dataset_name: str, data_dir: Path) -> dict:
    """Return {'D1': df_test_d1, 'D2': df_test_d2} for dual-test evaluation.

    Both are canonical test splits generated by prepare_all_datasets; they
    differ only in the source distribution (original vs causal Fair Data).
    """
    return {
        "D1": pd.read_csv(data_dir / dataset_name / "D1_test.csv"),
        "D2": pd.read_csv(data_dir / dataset_name / "D2_test.csv"),
    }


def _skip(path: Path, label: str) -> bool:
    """Skip a (cond, model, dataset) entry if its output CSV already exists."""
    if path.exists():
        print(f"  [SKIP] {label} already exists.")
        return True
    return False


