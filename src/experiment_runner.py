def run_all_experiments(model_id: str, model, tokenizer, datasets: list, results_dir: Path, data_dir: Path, n_examples: int = 10):
    """Run all experiment conditions for one already-loaded model.

    All conditions consume the canonical split files generated by
    fair_data.prepare_all_datasets; no split is recomputed here.

    The DEMO_SEED env var controls the demonstration sampling seed (default
    42).

    Args:
        model_id (str): HuggingFace model identifier.
        model: Loaded AutoModelForCausalLM.
        tokenizer: Corresponding tokenizer.
        datasets (list): Dataset names to evaluate.
        results_dir (Path): Root directory for results.
        data_dir (Path): Root directory for data files.
        n_examples (int): Number of few-shot examples.
    """
    model_tag = model_id.replace("/", "-").replace(".", "-")
    demo_seed = int(os.environ.get("DEMO_SEED", SEED))
    if demo_seed != SEED:
        print(f"[experiment_runner] DEMO_SEED={demo_seed}: running demonstration-dependent conditions only.")

    for dataset_name in datasets:
        results_out = results_dir / dataset_name / model_tag
        results_out.mkdir(parents=True, exist_ok=True)
        print(f"\n  Dataset: {dataset_name.upper()}")

        _run_icl(dataset_name, model, tokenizer, model_id, model_tag, results_out, data_dir, n_examples, demo_seed)

        _run_cot(dataset_name, model, tokenizer, model_id, model_tag, results_out, data_dir, demo_seed)

        if model_id in HF_D4R_MODELS:
            _run_d4r(dataset_name, model, tokenizer, model_id, model_tag, results_out, data_dir, demo_seed)

        if demo_seed == SEED:
            _run_zeroshot(dataset_name, model, tokenizer, model_id, model_tag, results_out, data_dir)

        _run_decontam(dataset_name, model, tokenizer, model_tag, results_out, data_dir, n_examples, demo_seed)

